"""Copilot page: cited answers about the selected patient (Phase 5; USER_FLOWS F6; ADR-040).

Thin: one call to ``ui_runtime.ask`` (routing, tools, retrieval, generation and citation
validation all happen in services). This module lays out the result:

- the answer's statements, each with its citation ids, labelled as generated text;
- every cited source in an expander with its **exact stored text** (``st.text``, never Markdown),
  document, page, date, review status and identity label, plus the full page on request and a
  button that opens the document on the Documents page;
- sources that were retrieved but not cited, the route and tool activity, fixed notes;
- refusals, abstentions and validation failures as fixed texts (failed answers are never shown).

No conversation history is kept: ``st.session_state`` holds identifiers only (Task 2.9b rule), and
questions and answers contain patient information. The answer is rendered and discarded.
"""

from typing import Any

import streamlit as st

from app.services import copilot, ui_runtime
from app.ui import texts
from app.ui.views import (
    DOCUMENT_KEY,
    _embedder,
    _request_selection,
    _reranker,
    attempt,
)

PAGE_KEY = "page"


def copilot_page(settings: Any, patient: Any) -> None:
    st.header("Copilot")
    synthetic = " (synthetic)" if patient.is_synthetic else ""
    st.markdown(f"Answering about: **{patient.display_name}**{synthetic}")
    st.caption(texts.COPILOT_NOTE)
    with st.form("copilot"):
        question = st.text_input("Ask about this patient's records", max_chars=500)
        submitted = st.form_submit_button("Ask")
    if not submitted or not question.strip():
        return
    with st.spinner("Checking this patient's records..."):
        answer = attempt(
            lambda: ui_runtime.ask(
                settings,
                patient.id,
                question,
                embedder=_embedder(settings),
                reranker=_reranker(settings),
            )
        )
    if answer is None:
        return
    show_answer(patient, answer)  # rendered now, never kept in session state


def _show_status(answer: Any) -> None:
    level, label = texts.copilot_status(answer.status.value)
    getattr(st, level)(answer.message or label)


def _source_label(source: Any) -> str:
    where = f"page {source.page_number} of {source.filename or 'a document'}"
    if source.kind.value == "fact":
        date = source.effective_date.isoformat() if source.effective_date else "no date"
        return f"[{source.source_id}] {source.analyte} · {date} · {where}"
    date = source.document_date.isoformat() if source.document_date else "date unknown"
    return f"[{source.source_id}] passage · {date} · {where}"


def _show_source(patient: Any, source: Any, *, key: str) -> None:
    with st.expander(_source_label(source)):
        if source.kind.value == "fact":
            shown = f"{source.comparator or ''}{source.value or source.qualitative or ''}"
            st.text(f"Shown value: {shown} {source.unit or ''}".rstrip())
            st.text(f"As printed: {source.value_raw or ''} {source.unit_raw or ''}".rstrip())
            if source.ref_range_raw:
                st.text(f"Printed reference range: {source.ref_range_raw}")
            st.caption(f"Status: {texts.review_status_label(source.review_status or '')}")
            if source.corrected:
                st.caption("The shown value is a reviewer's correction; the printed value is kept.")
            if source.in_conflict:
                st.warning("Another stored result for this test and date disagrees.")
        if source.identity_check != "match":
            st.warning("Identity not confirmed for this document.")
        if source.parse_method == "ocr":
            st.warning("OCR text - unverified; compare with the original page.")
        st.text("Exact source text:")
        st.text(source.excerpt)
        page = attempt(
            lambda: copilot.source_page(patient.id, source.document_id, source.page_number)
        )
        st.text(f"Full page {source.page_number} as stored:")
        st.text(page if page else "The page is not available.")
        # A callback runs on the next rerun even though the answer itself is not re-rendered.
        st.button(
            "Open this document",
            key=f"{key}-open",
            on_click=_open_document,
            args=(source.document_id,),
        )


def _open_document(document_id: str) -> None:
    _request_selection(DOCUMENT_KEY, document_id)
    _request_selection(PAGE_KEY, "Documents")


def show_answer(patient: Any, answer: Any) -> None:
    _show_status(answer)
    if answer.claims:
        st.subheader("Answer")
        st.caption(
            f"Generated by MediMind ({answer.generator}) from the cited sources and checked "
            "against them. The exact source text is below."
        )
        for claim in answer.claims:
            cites = " ".join(f"[{c}]" for c in claim.citations)
            prefix = "Calculation: " if claim.kind == "calculation" else ""
            st.text(f"• {prefix}{claim.text} {cites}".rstrip())
    for missing in answer.missing:
        st.caption(f"Not found: {missing}")
    for note in answer.notes:
        st.caption(ui_runtime.COPILOT_NOTES.get(note, note))
    if answer.issues:
        st.markdown("**Why the answer was withheld:**")
        for code in sorted({i.code for i in answer.issues}):
            st.text(f"- The answer {texts.citation_issue_text(code)}.")
    cited = set(answer.cited)
    if cited:
        st.subheader("Sources")
        for source in answer.cited_sources:
            _show_source(patient, source, key=f"cited-{source.source_id}")
    others = [s for s in answer.sources if s.source_id not in cited]
    if others:
        label = "Retrieved sources" if not cited else "Retrieved but not cited"
        st.subheader(label)
        for source in others:
            _show_source(patient, source, key=f"other-{source.source_id}")
    with st.expander("How this answer was produced"):
        st.text(
            f"Route: {texts.ROUTE_LABELS.get(answer.plan.route.value, answer.plan.route.value)}"
        )
        st.text(f"Intent: {answer.plan.intent.value}")
        if answer.plan.analytes:
            st.text(f"Tests recognised: {', '.join(answer.plan.analytes)}")
        if answer.plan.date_from or answer.plan.date_to:
            st.text(f"Dates: {answer.plan.date_from} to {answer.plan.date_to}")
        st.text(f"Rules: {', '.join(answer.plan.reasons) or '-'}")
        st.text(f"Steps: {', '.join(answer.activity) or '-'}")
        if answer.generator:
            st.text(f"Generator: {answer.generator} ({answer.generator_version})")
        st.text(f"Time: {answer.timings_ms.get('total', 0)} ms")
