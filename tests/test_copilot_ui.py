"""Copilot page of the local UI (Phase 5; ADR-040) with Streamlit's ``AppTest``.

``ui_runtime.ask`` and ``copilot.source_page`` are replaced by stand-ins: no database, model or
retrieval. The page must show validated claims with their citations, the exact source text,
fixed texts for refusals, abstentions and validation failures (never a withheld answer), and keep
no conversation in session state.
"""

import datetime as dt
import uuid

import pytest

from app.answering.model import (
    CitationIssue,
    CopilotStatus,
    DraftClaim,
    EvidenceItem,
    Intent,
    RefusalKind,
    Route,
    RoutePlan,
    SourceKind,
)
from app.services import copilot, ui_runtime
from tests.test_ui import SECRET, _app, _texts, backend  # noqa: F401 (fixture)

DOC = str(uuid.uuid4())
EXCERPT = "HbA1c\t6.6\t%\t4.0 - 5.6"
SOURCE = EvidenceItem(
    source_id="F1", kind=SourceKind.FACT, document_id=DOC, page_number=1, excerpt=EXCERPT,
    filename="report-a.pdf", identity_check="unknown", fact_id=str(uuid.uuid4()),
    analyte="HbA1c", value="6.9", unit="%", value_raw="6.6", unit_raw="%",
    ref_range_raw="4.0 - 5.6", effective_date=dt.date(2022, 2, 13), date_precision="day",
    review_status="corrected", value_source="human_correction", in_conflict=True,
)  # fmt: skip
PLAN = RoutePlan(
    route=Route.STRUCTURED_FACTS, intent=Intent.ON_DATE, analytes=("HbA1c",),
    date_from=dt.date(2022, 2, 13), date_to=dt.date(2022, 2, 13), reasons=("exact_date",),
)  # fmt: skip
CLAIM = DraftClaim(
    text='HbA1c: 6.9 % on 2022-02-13 (corrected by a reviewer; the report printed "6.6 %").',
    citations=("F1",),
)
WITHHELD = "HbA1c 7.7 % proves diabetes"  # a generated claim that failed validation


def answer(status: CopilotStatus, **kwargs) -> copilot.CopilotAnswer:
    base = {"status": status, "plan": PLAN, "message": None, "generator": "extractive"}
    base.update(kwargs)
    return copilot.CopilotAnswer(**base)


@pytest.fixture
def ask(backend, monkeypatch):  # noqa: F811
    state = {"answer": None, "calls": [], "fail": None}
    installed = backend()

    def fake(settings, patient_id, question, *, embedder, reranker, generator=None):
        state["calls"].append((patient_id, question))
        if state["fail"] is not None:
            raise state["fail"]
        return state["answer"]

    monkeypatch.setattr(ui_runtime, "ask", fake)
    monkeypatch.setattr(copilot, "source_page", lambda pid, doc, page: "FULL PAGE TEXT\n" + EXCERPT)
    state["backend"] = installed
    return state


def _ask(question: str = "What was my HbA1c on 13/02/2022?"):
    at = _app("Copilot")
    at.text_input[0].set_value(question)
    at.button[0].click().run()
    return at


def test_the_copilot_page_is_listed_and_names_the_patient(ask) -> None:
    at = _app("Copilot")
    assert not at.exception
    assert "Answering about: **Asha Fictional** (synthetic)" in _texts(at)
    assert "does not diagnose" in _texts(at)


def test_an_answer_shows_claims_citations_and_exact_sources(ask) -> None:
    ask["answer"] = answer(
        CopilotStatus.ANSWERED, claims=(CLAIM,), sources=(SOURCE,), cited=("F1",),
        activity=("tool:results_on_date",),
    )  # fmt: skip
    at = _ask()
    shown = _texts(at)
    assert ask["calls"] == [(ask["backend"].synthetic.id, "What was my HbA1c on 13/02/2022?")]
    assert CLAIM.text in shown and "[F1]" in shown
    assert EXCERPT in shown  # exact source text
    assert "FULL PAGE TEXT" in shown  # page navigation
    assert "As printed: 6.6 %" in shown and "Shown value: 6.9 %" in shown
    assert "Identity not confirmed" in shown
    assert "disagrees" in shown  # conflict flag
    assert "Generated by MediMind (extractive)" in shown
    assert "tool:results_on_date" in shown
    assert any(b.label == "Open this document" for b in at.button)


def test_opening_a_source_selects_the_document_page(ask) -> None:
    b = ask["backend"]
    document = b.add_document(b.synthetic)
    source = SOURCE.model_copy(update={"document_id": str(document.id)})
    ask["answer"] = answer(
        CopilotStatus.ANSWERED, claims=(CLAIM,), sources=(source,), cited=("F1",)
    )
    at = _ask()
    (button,) = [b for b in at.button if b.label == "Open this document"]
    button.click().run()
    assert at.session_state["page"] == "Documents"
    assert at.session_state["document_id"] == str(document.id)
    assert not at.exception


@pytest.mark.parametrize(
    ("status", "message"),
    [
        (CopilotStatus.REFUSED, "cannot recommend"),
        (CopilotStatus.UNSUPPORTED, "general medical explanations"),
        (CopilotStatus.INSUFFICIENT_EVIDENCE, "Nothing is guessed"),
    ],
)
def test_refusals_and_abstentions_show_fixed_text_only(ask, status, message) -> None:
    from app.answering.guardrails import REFUSAL_MESSAGES

    text = {
        CopilotStatus.REFUSED: REFUSAL_MESSAGES[RefusalKind.ADVICE],
        CopilotStatus.UNSUPPORTED: REFUSAL_MESSAGES[RefusalKind.GENERAL_KNOWLEDGE],
        CopilotStatus.INSUFFICIENT_EVIDENCE: copilot.INSUFFICIENT_MESSAGE,
    }[status]
    ask["answer"] = answer(status, message=text)
    at = _ask("Should I stop my tablets?")
    assert message in _texts(at)
    assert "Answer" not in [s.value for s in at.subheader]


def test_a_failed_validation_never_shows_the_generated_text(ask) -> None:
    ask["answer"] = answer(
        CopilotStatus.VALIDATION_FAILED,
        message=copilot.VALIDATION_FAILED_MESSAGE,
        sources=(SOURCE,),
        issues=(CitationIssue(code="unknown_source", claim_index=0, source_id="F9"),),
    )
    at = _ask()
    shown = _texts(at)
    assert "failed citation checks" in shown
    assert "cited a source that was not provided (fabricated)" in shown
    assert WITHHELD not in shown
    assert EXCERPT in shown  # retrieved sources stay inspectable


def test_partial_answers_list_what_is_missing_and_notes(ask) -> None:
    ask["answer"] = answer(
        CopilotStatus.PARTIAL, claims=(CLAIM,), sources=(SOURCE,), cited=("F1",),
        missing=("No usable TSH result with a date.",), notes=("no_time_given",),
    )  # fmt: skip
    shown = _texts(_ask())
    assert "Not found: No usable TSH result with a date." in shown
    assert "most recent result is shown" in shown


def test_errors_show_a_fixed_reason_not_the_message(ask) -> None:
    from app.llm.provider import LlmError

    ask["fail"] = LlmError(SECRET, kind="external_not_allowed")
    at = _ask()
    assert "External language-model endpoints are disabled" in _texts(at)
    assert SECRET not in _texts(at)


def test_no_question_or_answer_is_kept_in_session_state(ask) -> None:
    ask["answer"] = answer(
        CopilotStatus.ANSWERED, claims=(CLAIM,), sources=(SOURCE,), cited=("F1",)
    )
    at = _ask("What was my HbA1c on 13/02/2022?")
    kept = repr(at.session_state)  # our keys: page, patient, widget flags; never the conversation
    assert "HbA1c" not in kept and "6.9" not in kept


def test_without_a_patient_the_copilot_asks_for_one(backend, monkeypatch) -> None:  # noqa: F811
    b = backend()
    b.patients.clear()
    at = _app("Copilot")
    assert "Select or create a patient" in _texts(at)


