def _settings(**changes):
    from app.core.config import Settings

    return Settings(_env_file=None, **changes)


def test_the_default_generator_is_extractive_and_the_mode_is_the_frozen_one() -> None:
    from app.answering.generate import ExtractiveGenerator

    settings = _settings()
    assert isinstance(ui_runtime.make_generator(settings), ExtractiveGenerator)
    assert settings.copilot_retrieval_mode == "lexical"
    assert ui_runtime.copilot_mode(settings) == "lexical"


def test_an_llm_needs_a_url_and_a_model_and_is_local_by_default() -> None:
    from app.answering.generate import LlmGenerator
    from app.llm.provider import LlmError

    with pytest.raises(LlmError) as missing:
        ui_runtime.make_generator(_settings(llm_provider="openai_compatible"))
    assert missing.value.kind == "not_configured"
    with pytest.raises(LlmError) as external:
        ui_runtime.make_generator(
            _settings(
                llm_provider="openai_compatible",
                llm_base_url="https://api.example.com/v1",
                llm_model="m",
            )
        )
    assert external.value.kind == "external_not_allowed"
    local = ui_runtime.make_generator(
        _settings(
            llm_provider="openai_compatible",
            llm_base_url="http://127.0.0.1:11434/v1",
            llm_model="m",
        )
    )
    assert isinstance(local, LlmGenerator) and local.provider.is_local


def test_a_mode_without_its_models_is_not_used() -> None:
    assert ui_runtime.copilot_mode(_settings(copilot_retrieval_mode="hybrid_rerank")) is None
